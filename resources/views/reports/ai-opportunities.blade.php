    <h2>الفكرة ببساطة</h2>
    <div class="note"><strong>نضيف مساعدًا ذكيًا داخل البوابة</strong> يساعد الموظف والمدير على الوصول للمعلومة، تلخيص المعاملات، وكتابة الردود بسرعة. المساعد يقترح فقط، والموظف يراجع ويعتمد.</div>
    <p>المساعد لا يستبدل الموظف، ولا يأخذ قرارات طبية أو قانونية، ولا يرسل أي شيء أو يغير أي حالة دون موافقة واضحة.</p>

    <h2>ماذا سيقدم المساعد؟</h2>
    <h3>1. البحث بطريقة سهلة</h3>
    <p>يسأل الموظف: أين نموذج موافقة التنويم؟ ما الشكاوى التي لم يتم الرد عليها؟ ما الخدمات المتاحة في فرع السويدي؟ ويعرض المساعد الإجابة ورابط التفاصيل.</p>
    <h3>2. تلخيص أي معاملة</h3>
    <p>في الشكوى أو الاستفسار أو المراسلة أو التحويل، يوضح ما حدث، الحالة الحالية، ما تم، ما ينقص، المسؤول التالي، وهل يوجد تأخير.</p>
    <h3>3. كتابة الردود والخطابات</h3>
    <p>يكتب ردًا رسميًا مقترحًا بالعربية أو الإنجليزية. الموظف يراجعه ويعدله ثم يرسله بنفسه. ينفع ذلك في الشكاوى والاستفسارات والمراسلات وطلبات البيانات والتفتيش.</p>
    <h3>4. معرفة ما يحتاج اهتمامًا اليوم</h3>
    <p>يعرض الطلبات المتأخرة، الموافقات المعلقة، الردود غير المرسلة، المستندات الناقصة، الزيارات التفتيشية، الأعطال، وطلبات الإجازة والغياب التي تحتاج إجراء.</p>
    <h3>5. تلخيص التعاميم واللوائح</h3>
    <p>يقترح أهم النقاط، الإدارات المعنية، المطلوب من كل إدارة، والموعد النهائي. يعتمد الموظف الملخص قبل نشره.</p>
    <h3>6. مساعدة المدير في فهم الأرقام</h3>
    <p>يمكن للمدير أن يسأل: كم شكوى مفتوحة هذا الشهر؟ ما أكثر فرع لديه أعطال؟ كم طلبًا ينتظر الرد؟ ويعرض المساعد الرقم والفترة التي تم الحساب عليها.</p>
    <h3>7. توجيه الشكاوى والاستفسارات</h3>
    <p>يقترح القسم المسؤول ونوع الطلب ودرجة الأولوية، ثم يراجع الموظف الاقتراح قبل اعتماده.</p>
    <h3>8. البحث عن طبيب أو خدمة</h3>
    <p>يجيب عن مكان الطبيب أو الخدمة ومواعيدها والمعلومات المنشورة عنها، دون تشخيص أو وصف علاج.</p>
    <h3>9. التأكد من اكتمال طلب التحويل</h3>
    <p>ينبه إلى البيانات أو المستندات الناقصة قبل إرسال طلب التحويل، دون أن يقبله أو يرفضه.</p>
    <h3>10. ترتيب ملف المطالبة أو القضية</h3>
    <p>يلخص الموضوع ويرتب الأحداث ويوضح المستندات الموجودة والناقصة والمواعيد القادمة، دون تقديم حكم قانوني.</p>
    <h3>11. تلخيص الزيارة التفتيشية</h3>
    <p>ينشئ ملخصًا للملاحظات، المسؤول عن كل ملاحظة، موعد الرد، وما يحتاج تصعيدًا.</p>
    <h3>12. مساعدة فريق الدعم الفني</h3>
    <p>يلخص بلاغ العطل، يقترح القسم المناسب، ويعرض بلاغات مشابهة وخطوات أولية للفحص دون الدخول على الأجهزة.</p>
    <h3>13. مراجعة بيانات حاسبة التنويم</h3>
    <p>ينبه إلى الحقول الناقصة أو البيانات غير المتناسقة قبل إصدار التقرير.</p>
    <h3>14. استقبال طلب الموعد بطريقة حوارية</h3>
    <p>يسأل عن الفرع والتخصص والطبيب والوقت المناسب، ثم يجهز طلبًا مرتبًا للمراجعة قبل حفظه. لا يضمن الموعد ولا يقرر أولوية طبية.</p>
    <h3>15. تجهيز رسائل الجوال والبريد</h3>
    <p>يقترح رسالة لتذكير الموظف أو طلب مستند ناقص أو إبلاغه بتغيير الحالة، مع مراجعتها قبل الإرسال.</p>
    <h3>16. مساعدة الموارد البشرية</h3>
    <p>يلخص الإجازات والغياب والتدريب وطلبات الموظفين، ويقترح الرد والخطوة التالية دون قبول أو رفض بدل المختص.</p>

